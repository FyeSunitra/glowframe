export function translateText(locale: MenuLocale, value: string) {
  if (locale === 'en') return value;
  const translated = thByEnglish[value];
  if (translated) return translated;

  const week = value.match(/^Week (\d+)$/);
  if (week) return `สัปดาห์ที่ ${week[1]}`;

  const month = value.match(/^Month (\d+)$/);
  if (month) return `เดือนที่ ${month[1]}`;

  const days = value.match(/^(\d+(?:\.\d+)?) days$/);
  if (days) return `${days[1]} วัน`;

  const photos = value.match(/^(\d+) photos$/);
  if (photos) return `${photos[1]} รูป`;

  const dispute = value.match(/^Dispute (.+)$/);
  if (dispute) return `ข้อพิพาท ${dispute[1]}`;

  const edit = value.match(/^Edit — (.+)$/);
  if (edit) return `แก้ไข — ${edit[1]}`;

  const preview = value.match(/^Preview — (.+)$/);
  if (preview) return `ดูตัวอย่าง — ${preview[1]}`;

  const refund = value.match(/^(.+ THB) will be refunded to the customer\.$/);
  if (refund) return `${refund[1]} จะถูกคืนให้ลูกค้า`;

  return value;
}

export function translateStatus(locale: MenuLocale, value: string) {
  const normalized = value
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .replace(/_/g, ' ')
    .replace(/-/g, ' ')
    .replace(/\b\w/g, (c) => c.toUpperCase());

  return translateText(locale, normalized);
}
